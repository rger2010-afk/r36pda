// UTF-8 декодер: возвращает код-точку или -1
static inline int utf8_decode(const unsigned char *s, int *len) {
    if (s[0] < 0x80) { *len = 1; return s[0]; }
    if ((s[0] & 0xE0) == 0xC0 && (s[1] & 0xC0) == 0x80) {
        *len = 2; return ((s[0] & 0x1F) << 6) | (s[1] & 0x3F);
    }
    if ((s[0] & 0xF0) == 0xE0 && (s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80) {
        *len = 3; return ((s[0] & 0x0F) << 12) | ((s[1] & 0x3F) << 6) | (s[2] & 0x3F);
    }
    *len = 1; return -1;
}

// Возвращает глиф для код-точки, nullptr если нет
static inline const Glyph *font_glyph(int cp) {
    if (cp == 0x0401) return &FONT_CYR_IO;
    if (cp == 0x0451) return &FONT_CYR_io;
    if (cp >= 0x0410 && cp <= 0x042F) return &FONT_CYR_UPPER[cp - 0x0410];
    if (cp >= 0x0430 && cp <= 0x044F) return &FONT_CYR_LOWER[cp - 0x0430];
    if (cp >= 32 && cp <= 126) return &FONT_ASCII[cp - 32];
    return nullptr;
}

